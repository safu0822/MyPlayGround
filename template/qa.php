        <summary>ダイビングスタイルは、1日船に乗りっぱなしですか？</summary>
        <p>
          基本的には朝の出港から当日の3ダイブが終了するまで戻りません。
          <br>2ダイブで終了の方は、船上でのんびりお過ごし下さい。
          <br>お弁当（￥800）や 飲み物はこちらでご用意します。
          <br>お弁当をご自分で用意される方は、事前にご連絡ください。船にはお湯もご用意しております。
          <br>お昼休憩は近くの港か、波の少ない所で停泊しての休憩になります。
          <br>
        </p>
