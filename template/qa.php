        <summary>ダイビングポイントはどんなところに行くんですか？</summary>
        <p>
          西表島近海（北側、西側）をメインに潜っています。
          <br>その日の海況、リクエストに応じてイチオシのポイントへご案内致します。
          <br>南側エリア、仲之神島、波照間島への遠征も行っていますが、船も小さい為積極的な遠征は行っておりません。
        </p>
      </details>
      <details class="qa-1">
        <summary>ダイビングボートにトイレはありますか？また、どんなボートですか？</summary>
        <p>
          ダイビングボートには簡易シャワー・簡易トイレ付きです。小型船ながらもトイレ内は着替えができる程のスペースもございます。
          <br>船の大きさは32フィート（約10m）、定員14名のボートを最大6名で広々ご利用になれます。雨風も防げる横テント付きで雨の日も快適です。
        </p>
      </details>
