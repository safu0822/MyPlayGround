      <details class="qa-1">
        <summary>天候で定期船が全部欠航になることはありますか？</summary>
        <p>
          台風などによって海況が著しく悪くなった場合、全便欠航する場合があります。運航状況は当日にならないとわかりません。低気圧の影響によっても全便欠航になる場合がございます。
          <br>石垣空港到着後、欠航となった場合はまずお電話下さい。石垣市内の宿泊先等のご紹介もさせていただきます。
          <br>また、台風接近などでお帰りの船が欠航になりそうだと予測できる場合、延泊または、帰る日程の繰り上げなどのご案内を致します。
        </p>
      </details>
